package org.apache.activemq.maven.xbean;

import static org.apache.activemq.maven.xbean.SampleSupport.NAMESPACE;
import static org.apache.activemq.maven.xbean.SampleSupport.QUIET_LOG;
import static org.apache.activemq.maven.xbean.SampleSupport.sample;
import static org.apache.activemq.maven.xbean.SampleSupport.load;
import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Set;
import java.util.stream.Stream;

import org.apache.xbean.spring.generator.DocumentationGenerator;
import org.apache.xbean.spring.generator.GeneratorPlugin;
import org.apache.xbean.spring.generator.NamespaceMapping;
import org.apache.xbean.spring.generator.WikiDocumentationGenerator;
import org.apache.xbean.spring.generator.XmlMetadataGenerator;
import org.apache.xbean.spring.generator.XsdGenerator;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

/**
 * The files under samples/expected were produced once by
 * org.apache.xbean:maven-xbean-plugin:4.31 with QDox 1.12.1 over samples/src,
 * with the date line of the two Spring files replaced by a bare {@code #} as
 * activemq-spring's build used to do. Every byte the new loader and writer
 * produce must match them.
 */
public class GeneratedOutputTest {

    @Rule
    public TemporaryFolder temp = new TemporaryFolder();

    @Test
    public void outputMatchesTheLegacyPluginByteForByte() throws Exception {
        File out = temp.newFolder("out");
        File schema = new File(out, "sample.xsd");
        NamespaceMapping namespace = load("src", Set.of("org.apache.activemq.xbean.sample.Excluded"));

        GeneratorPlugin[] generators = {
            new XmlMetadataGenerator(out.getAbsolutePath(), schema, false, false),
            new DocumentationGenerator(schema),
            new XsdGenerator(schema, false),
            new WikiDocumentationGenerator(schema),
        };
        for (GeneratorPlugin generator : generators) {
            generator.setLog(QUIET_LOG);
            generator.generate(namespace);
        }
        SpringMetadataWriter.writeHandlers(out, NAMESPACE);
        SpringMetadataWriter.writeSchemas(out, NAMESPACE, schema);

        Path expectedRoot = sample("expected").toPath();
        List<Path> expectedFiles;
        try (Stream<Path> walk = Files.walk(expectedRoot)) {
            expectedFiles = walk.filter(Files::isRegularFile).sorted().toList();
        }
        assertTrue("no expected files found", expectedFiles.size() >= 6);
        for (Path expected : expectedFiles) {
            Path relative = expectedRoot.relativize(expected);
            Path actual = out.toPath().resolve(relative);
            assertTrue("not generated: " + relative, Files.isRegularFile(actual));
            assertEquals(relative.toString(),
                    Files.readString(expected, StandardCharsets.ISO_8859_1),
                    Files.readString(actual, StandardCharsets.ISO_8859_1));
        }
    }

    @Test
    public void springFilesCarryNoTimestampAndMergeExistingEntries() throws Exception {
        File out = temp.newFolder("meta");
        SpringMetadataWriter.writeHandlers(out, "http://example.com/schema/b");
        SpringMetadataWriter.writeHandlers(out, "http://example.com/schema/a");
        String handlers = Files.readString(new File(out, "META-INF/spring.handlers").toPath(), StandardCharsets.ISO_8859_1);
        assertEquals("#Generated by xbean-spring\n"
                + "#\n"
                + "http\\://example.com/schema/a=org.apache.xbean.spring.context.v2.XBeanNamespaceHandler\n"
                + "http\\://example.com/schema/b=org.apache.xbean.spring.context.v2.XBeanNamespaceHandler\n", handlers);
    }
}
